#!/usr/bin/env python3
"""CPU-only in-process route: one pinned CPU model, host RAM, no target IP/DMA.

This module reuses the existing local-harness CPU artifact (its pinned source
closure, structural wrapper and ABI) and adds only the two things a CPU-only run
needs: a host that serves the CPU's own instruction/data bus from RAM, and an
assertion-instrumented build of that same wrapper.  No target model is planned,
built, linked or instantiated.

The public API is deliberately small so the unified entry (agent D) can call it:

    build_cpu_only(config_path, cache, output=None, *, assertions=False) -> dict
    run_cpu_only(config_path, cache, output, *, records=None, fuzz=None,
                 max_ticks=None, assertions=None, fault=None, ...) -> dict

``build_cpu_only`` returns the selected model archive list (always exactly one
CPU archive) and the linked host. ``run_cpu_only`` runs an external child
process, so a DUT assertion that terminates the Verilator process still leaves
the input/case and the assertion text in the captured stderr.
"""
