# The normal program is a real polling loop.  Inputs land in one RAM word and the
# CPU stores input+1 to the adjacent result word; every case therefore needs an
# instruction fetch, a data load, an ALU operation, a data store and a jump.
_PROGRAM_WORDS = (
    0x000112b7,  # lui   x5, 0x11       -> x5 = mailbox page
    0x0002a303,  # lw    x6, 0(x5)      -> input word
    0x000130393,  # addi  x7, x6, 1      -> result
    0x00072a223,  # sw    x7, 4(x5)      -> store result
    0xff5ff06f,  # jal   x0, -12        -> back to the load
)
# The assertion case must not issue a data access before the declared fault, so
# this program only fetches: an infinite `jal x0, 0`.
_FAULT_PROGRAM_WORDS = (0x0000006f,)
# The same word is the end-of-batch halt for a generated-program batch: after the
# last case's trailer nothing else may execute, so the CPU spins on one address.
_HALT_WORD = _FAULT_PROGRAM_WORDS[0]

# --- generated-program batches ------------------------------------------------
#
# A program case is a real RV32 program generated by the repository's existing F1
# generator (``myfuzz.fuzz.rv32_program.generate_program``) and admitted by the
# existing F1 gate (``myfuzz.fuzz.f1_program_gate.validate_f1_program_record``).
# This module only builds the firmware around it: a two-word preamble that sets
# ``x18`` to the case's data window, the program itself, one trailer word that
# stores the case's completion word, and a NOP sled so the next case cannot start
# before this one has been observed.
#
# No instruction here is hand-encoded: the preamble, trailer and sled are built by
# the repository's existing RV32I source emitter
# (``myfuzz.scenario.rv32i_sources.Rv32iInstruction``), and the halt word is the
# existing constant above.
PROGRAM_DATA_WORDS = 16          # data window per case (64 bytes)
PROGRAM_MAX_WORDS = 16           # F1 generator bound
PROGRAM_CASE_STRIDE = 0x100      # one case's slot and one case's window
PROGRAM_SLED_WORDS = 8
PROGRAM_DONE_OFFSET = PROGRAM_DATA_WORDS * 4
PROGRAM_DONE_SENTINEL = 0xffffffff
#: The data word a program case's trailer stores is checked against this value.
PROGRAM_DONE_VALUE = 0

