class CpuOnlyError(RuntimeError):
    """A CPU-only admission/build/run failure, refused by name."""


def _sha(value: bytes | str) -> str:
    if isinstance(value, str):
        value = value.encode()
    return hashlib.sha256(value).hexdigest()


def _read_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def _write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + '\n', encoding='utf-8')


def _normalise_path(path: Path) -> Path:
    return path.resolve()


def load_cpu_only_config(config_path: str | Path = DEFAULT_CONFIG) -> dict:
    """Load and structurally validate one CPU-only scenario."""
    path = Path(config_path)
    if not path.is_file():
        raise CpuOnlyError('cpu-only-config-missing:' + str(path))
    document = _read_json(path)
    if not isinstance(document, dict) or document.get('schema_version') != SCHEMA_VERSION:
        raise CpuOnlyError('cpu-only-config-schema')
    required = {'cpu_profile', 'instance_id', 'ram_base', 'ram_size', 'boot_address',
                'program_address', 'mailbox_address', 'result_address',
                'reset_assert_ticks', 'reset_release_ticks', 'max_ticks'}
    missing = sorted(required - set(document))
    if missing:
        raise CpuOnlyError('cpu-only-config-missing-fields:' + ','.join(missing))
    for key in ('ram_base', 'ram_size', 'boot_address', 'program_address',
                'mailbox_address', 'result_address', 'reset_assert_ticks',
                'reset_release_ticks', 'max_ticks'):
        value = document[key]
        if type(value) is not int or value < 0:
            raise CpuOnlyError('cpu-only-config-invalid:' + key)
    if not 0 < document['ram_size'] <= 0x10000000:
        raise CpuOnlyError('cpu-only-config-invalid:ram_size')
    profile = ROOT / document['cpu_profile']
    if profile.suffix != '.json' or not profile.is_file():
        raise CpuOnlyError('cpu-only-profile-missing:' + document['cpu_profile'])
    if document.get('cpu_cache_digest') is not None:
        digest = document['cpu_cache_digest']
        if not isinstance(digest, str) or re.fullmatch(r'[0-9a-f]{64}', digest) is None:
            raise CpuOnlyError('cpu-only-config-invalid:cpu_cache_digest')
    observations = document.get('required_observations',
                                ['rvfi_valid', 'rvfi_pc_rdata', 'rvfi_insn'])
    if (not isinstance(observations, list)
            or any(not isinstance(item, str) or not item for item in observations)
            or len(set(observations)) != len(observations)):
        raise CpuOnlyError('cpu-only-config-invalid:required_observations')
    document['required_observations'] = observations
    fault = document.get('fault')
    if fault is not None:
        if not isinstance(fault, dict) or fault.get('kind') != 'spurious-data-rvalid':
            raise CpuOnlyError('cpu-only-fault-kind')
        if type(fault.get('tick')) is not int or not 1 <= fault['tick'] <= 100000:
            raise CpuOnlyError('cpu-only-fault-tick')
    source = document.get('cpu_artifact_source')
    if source is not None and source not in ('pinned', 'profile'):
        raise CpuOnlyError('cpu-only-artifact-source-invalid:' + str(source))
    wait = document.get('max_wait_cycles', 16)
    if type(wait) is not int or not 1 <= wait <= 1024:
        raise CpuOnlyError('cpu-only-config-invalid:max_wait_cycles')
    data_address = document.get('program_data_address')
    if data_address is not None and (type(data_address) is not int
                                     or data_address < 0 or data_address % 4):
        raise CpuOnlyError('cpu-only-config-invalid:program_data_address')
    for key, low, high in (('program_data_words', 4, 60),
                           ('program_max_words', 1, PROGRAM_MAX_WORDS)):
        value = document.get(key)
        if value is None:
            continue
        if type(value) is not int or not low <= value <= high:
            raise CpuOnlyError('cpu-only-config-invalid:' + key)
    document['_path'] = str(path.resolve())
    return document


def _artifact_cache_root(config: dict, *, create: bool = False) -> Path:
    raw = config.get('artifact_cache')
    if not isinstance(raw, str) or not raw:
        raise CpuOnlyError('cpu-only-artifact-cache-required')
    root = (ROOT / raw).resolve()
    if not root.is_dir():
        if not create:
            raise CpuOnlyError('cpu-only-artifact-cache-missing:' + str(root))
        # A profile-resolved artifact may be built into a cache root that does
        # not exist yet; the scenario names it, so this route may create it.
        root.mkdir(parents=True, exist_ok=True)
    return root


def _profile_path(artifact: dict) -> str | None:
    plan = artifact.get('plan')
    return plan.get('profile_path') if isinstance(plan, dict) else None


def find_cpu_artifact(config: dict) -> dict:
    """Locate the pinned CPU artifact in the existing local-harness cache.

    Only the CPU artifact is accepted: ``kind`` must be the CPU runtime and the
    profile path must match the config.  A target/DMA artifact is never selected.
    """
    cache_root = _artifact_cache_root(config)
    profile = config['cpu_profile']
    hint = config.get('cpu_cache_digest')
    matches = []
    for manifest in sorted(cache_root.glob('*/inputs/generated/artifact.json')):
        try:
            artifact = _read_json(manifest)
        except (OSError, ValueError):
            continue
        if (artifact.get('module_name') != 'local_runtime_cpu'
                or artifact.get('kind') != 'obi_cpu'
                or _profile_path(artifact) != profile):
            continue
        archive = manifest.parents[2] / 'obj' / 'Vlocal_runtime_cpu__ALL.a'
        structural = manifest.parents[0] / 'structural.sv'
        if not archive.is_file() or not structural.is_file():
            continue
        digest = manifest.parents[2].name
        matches.append(dict(digest=digest, cache_dir=str(manifest.parents[2]),
                            inputs=str(manifest.parents[1]), artifact=artifact,
                            runtime_archive=str(archive), structural_sv=str(structural)))
    if hint is not None:
        matches = [row for row in matches if row['digest'] == hint]
    if len(matches) != 1:
        raise CpuOnlyError('cpu-only-artifact-selection:%d matches for %s' %
                           (len(matches), profile))
    return matches[0]


def _harness_request(config: dict) -> dict:
    """The local-harness request one CPU profile is rendered with.

    It is derived from the scenario's own declarations (profile, instance name,
    reset windows) plus the optional ``max_wait_cycles`` override, so the same
    profile always renders the same artifact.
    """
    return dict(
        schema_version='local_harness.v1',
        profile_path=config['cpu_profile'],
        instance_id=config['instance_id'],
        reset_assert_ticks=config['reset_assert_ticks'],
        reset_release_ticks=config['reset_release_ticks'],
        max_wait_cycles=config.get('max_wait_cycles', 16),
    )


def render_profile_artifact(config: dict) -> dict:
    """Render the pinned CPU artifact from its component profile.

    Nothing here reads a previously generated artifact: the plan, the structural
    wrapper and the runtime artifact document are produced by the same
    local-harness pipeline that produced every pinned artifact in the tree, from
    the profile path the scenario names.  No Verilator compile happens here; the
    CPU-only model is compiled from the rendered sources afterwards.
    """
    from myfuzz.local_harness import (
        load_local_harness_request, plan_local_harness, render_local_driver,
        render_local_harness, render_local_runtime, verify_local_source_lock)
    request = load_local_harness_request(_harness_request(config))
    plan = plan_local_harness(request, base_dir=ROOT)
    verified = verify_local_source_lock(plan.profile, base_dir=ROOT)
    structural = render_local_harness(plan)
    runtime = render_local_runtime(plan, structural, verified, base_dir=ROOT)
    artifact = render_local_driver(runtime, base_dir=ROOT)
    return dict(
        renderer='myfuzz.local_harness.plan_local_harness+render_local_driver',
        request=_harness_request(config),
        artifact_digest=artifact.runtime_document['artifact_digest'],
        kind=artifact.runtime_document['kind'],
        module_name=artifact.runtime_document.get('module_name'),
        structural_sv=structural.wrapper_sv,
        abi_document=structural.abi_document,
        document=artifact.runtime_document,
        _artifact=artifact,
        _plan=plan,
    )


def _cache_artifacts(cache_root: Path, digest: str | None = None) -> list[dict]:
    """One row per generated artifact already published under ``cache_root``."""
    rows = []
    for manifest in sorted(cache_root.glob('*/inputs/generated/artifact.json')):
        try:
            artifact = _read_json(manifest)
        except (OSError, ValueError):
            continue
        if digest is not None and artifact.get('artifact_digest') != digest:
            continue
        if (artifact.get('module_name') != 'local_runtime_cpu'
                or artifact.get('kind') not in
                ('obi_cpu', 'wishbone_cpu', 'axi4_lite_cpu', 'axi4_cpu')):
            continue
        structural = manifest.parent / 'structural.sv'
        if not structural.is_file():
            continue
        rows.append(dict(digest=manifest.parents[2].name,
                         cache_dir=str(manifest.parents[2]),
                         inputs=str(manifest.parents[1]), artifact=artifact,
                         structural_sv=str(structural)))
    return rows


def resolve_cpu_artifact(config: dict) -> dict:
    """Select the pinned CPU artifact, resolving it from the component profile.

    ``cpu_artifact_source`` selects the path:

    * ``pinned`` -- the scenario names a ``cpu_cache_digest``; that published
      build is used as-is (the P0 contract, unchanged);
    * ``profile`` -- the artifact is rendered from ``cpu_profile`` and matched by
      its own ``artifact_digest``.  A miss is built with the local-harness build
      machinery into the scenario's ``artifact_cache`` and then reused.

    ``cache_hit``/``compiled_this_invocation`` are reported from what actually
    happened, never assumed.
    """
    hint = config.get('cpu_cache_digest')
    source = config.get('cpu_artifact_source')
    if source is None:
        source = 'pinned' if hint is not None else 'profile'
    if source not in ('pinned', 'profile'):
        raise CpuOnlyError('cpu-only-artifact-source-invalid:' + str(source))
    cache_root = _artifact_cache_root(config, create=(source == 'profile'))
    if source == 'pinned':
        selected = find_cpu_artifact(config)
        return dict(selected=selected, source='pinned', cache_hit=True,
                    compiled_this_invocation=False, observation=None,
                    build_digest=selected['digest'],
                    artifact_digest=selected['artifact'].get('artifact_digest'),
                    seconds=0.0)
    started = time.monotonic()
    rendered = render_profile_artifact(config)
    # Refuse a CPU this host cannot serve before anything is compiled: the
    # rendered role map is the same one the selected artifact would carry, so the
    # refusal name is unchanged and no Verilator build is spent on it.
    _check_bus_shape({'artifact': rendered['document']})
    rows = [row for row in _cache_artifacts(cache_root, rendered['artifact_digest'])
            if hint is None or row['digest'] == hint]
    if len(rows) > 1:
        raise CpuOnlyError('cpu-only-artifact-selection:%d matches for %s' %
                           (len(rows), rendered['artifact_digest']))
    if rows:
        return dict(selected=rows[0], source='profile', cache_hit=True,
                    compiled_this_invocation=False, observation=None,
                    build_digest=rows[0]['digest'],
                    artifact_digest=rendered['artifact_digest'],
                    rendered=dict(artifact_digest=rendered['artifact_digest'],
                                  kind=rendered['kind'], module_name=rendered['module_name'],
                                  renderer=rendered['renderer'],
                                  request=rendered['request']),
                    seconds=time.monotonic() - started)
    from myfuzz.local_harness.build import (
        LocalHarnessBuildError, build_local_harness_with_receipt)
    try:
        built = build_local_harness_with_receipt(
            rendered['_artifact'], base_dir=ROOT, cache_dir=cache_root)
    except LocalHarnessBuildError as error:
        raise CpuOnlyError('cpu-only-artifact-build-failed:' + str(error)) from error
    observation = built.observation_document()
    cache_dir = Path(str(observation.get('manifest_path', ''))).parent
    manifest = cache_dir / 'inputs/generated/artifact.json'
    if not manifest.is_file():
        raise CpuOnlyError('cpu-only-artifact-build-output-missing:' + str(cache_dir))
    artifact = _read_json(manifest)
    if artifact.get('artifact_digest') != rendered['artifact_digest']:
        raise CpuOnlyError('cpu-only-artifact-digest-mismatch:%s:%s' %
                           (artifact.get('artifact_digest'),
                            rendered['artifact_digest']))
    selected = dict(digest=cache_dir.name, cache_dir=str(cache_dir),
                    inputs=str(cache_dir / 'inputs'), artifact=artifact,
                    structural_sv=str(manifest.parent / 'structural.sv'))
    return dict(selected=selected, source='profile', cache_hit=False,
                compiled_this_invocation=bool(observation.get('compiled_this_invocation')),
                observation=observation, build_digest=selected['digest'],
                artifact_digest=rendered['artifact_digest'],
                rendered=dict(artifact_digest=rendered['artifact_digest'],
                              kind=rendered['kind'], module_name=rendered['module_name'],
                              renderer=rendered['renderer'],
                              request=rendered['request']),
                seconds=time.monotonic() - started)


def _model_key(selected: dict, model_kind: str) -> str:
    artifact = selected['artifact']
    build = artifact['structural_build']
    inputs = Path(selected['inputs'])
    rows = []
    for name in build['source_files']:
        path = inputs / name
        rows.append([name, _sha(path.read_bytes())])
    payload = {
        'schema': 'p0_cpu_only_model.v1',
        'artifact_digest': artifact.get('artifact_digest'),
        'model_kind': model_kind,
        'structural_sha256': _sha(Path(selected['structural_sv']).read_bytes()),
        'source_files': rows,
        'include_roots': build.get('include_roots', []),
        'defines': build.get('defines', []),
        'parameter_overrides': build.get('parameter_overrides', {}),
    }
    return _sha(json.dumps(payload, sort_keys=True, separators=(',', ':')))


def _verilator_build(selected: dict, config: dict, model_kind: str,
                     model_dir: Path) -> dict:
    artifact = selected['artifact']
    build = artifact['structural_build']
    inputs = Path(selected['inputs'])
    obj = model_dir / 'obj'
    archive = obj / 'Vlocal_cpu__ALL.a'
    flags = assertion_build_flags(rtl_assertions=(model_kind == 'assertion'))
    key = _model_key(selected, model_kind)
    stamp = model_dir / 'build.json'
    if stamp.is_file() and archive.is_file():
        try:
            document = _read_json(stamp)
            if (document.get('key') == key and document.get('archive') == str(archive)
                    and _sha(archive.read_bytes()) == document.get('archive_sha256')):
                return dict(status='cache_hit', model_kind=model_kind, model_dir=str(model_dir),
                            archive=str(archive), archive_sha256=document['archive_sha256'],
                            build_log=str(model_dir / 'build.log'), build_seconds=0.0)
        except (OSError, ValueError, KeyError):
            pass
    model_dir.mkdir(parents=True, exist_ok=True)
    if obj.exists():
        shutil.rmtree(obj)
    toolchain = _toolchain()
    verilator = toolchain['verilator']['path']
    include_roots = ['-I' + str((inputs / root).resolve()) for root in build.get('include_roots', [])]
    # prim_assert.sv chooses *dummy* macros whenever VERILATOR is predefined.  The
    # standard macros are read from the same pinned Ibex tree, not from a copied
    # header, so the assertion build names one extra include root only.
    if model_kind == 'assertion':
        upstream_prim = ROOT / 'third_party/rfuzz/upstream/ibex/vendor/lowrisc_ip/ip/prim/rtl'
        if not (upstream_prim / 'prim_assert_standard_macros.svh').is_file():
            raise CpuOnlyError('cpu-only-standard-assertion-macros-missing')
        include_roots.insert(0, '-I' + str(upstream_prim.resolve()))
    command = [
        verilator, '--cc', '--build', '-j', str(_build_jobs()), '-Wno-fatal',
        *flags, '--top-module', 'local_cpu', '--Mdir', str(obj), '-o', 'unused',
        str(Path(selected['structural_sv']).resolve()),
        *include_roots,
        *['-D' + value for value in build.get('defines', [])],
        *[str((inputs / name).resolve()) for name in build['source_files']],
    ]
    started = time.monotonic()
    result = subprocess.run(command, capture_output=True, text=True, cwd=ROOT)
    seconds = time.monotonic() - started
    (model_dir / 'build.log').write_text(
        '$ ' + ' '.join(command) + '\n' + result.stdout + result.stderr, encoding='utf-8')
    if result.returncode or not archive.is_file():
        raise CpuOnlyError('cpu-only-model-build-failed:%s:%s' %
                           (model_kind, (result.stdout + result.stderr)[-4000:]))
    archive_sha = _sha(archive.read_bytes())
    _write_json(stamp, dict(
        schema_version='p0_cpu_only_model.v1', key=key, model_kind=model_kind,
        command=command, archive=str(archive), archive_sha256=archive_sha,
        build_seconds=seconds, verilator=verilator,
        assertion_flags=list(flags)))
    return dict(status='built', model_kind=model_kind, model_dir=str(model_dir),
                archive=str(archive), archive_sha256=archive_sha,
                build_log=str(model_dir / 'build.log'), build_seconds=seconds)


def _port_map(artifact: dict) -> dict:
    rows = artifact.get('structural_abi', {}).get('ports', [])
    return {row['wrapper_name']: row for row in rows if isinstance(row, dict)}


def _role_map(artifact: dict) -> dict:
    result = {}
    for row in artifact.get('structural_abi', {}).get('ports', []):
        endpoint, role = row.get('endpoint_id'), row.get('role')
        if endpoint and role and row.get('direction') in ('input', 'output'):
            result[(endpoint, role)] = row['wrapper_name']
    return result


def _signal_status(artifact: dict, required: list[str]) -> dict:
    """Report CPU observations that the generated CPU wrapper really exports.

    A CPU whose profile does not export RVFI/trap is not silently reported as
    "0 retirements" or "no traps": the signal is unknown, and the scenario may
    require it (which refuses the route before a model is built).
    """
    physical = {row.get('physical_port') for row in
                artifact.get('structural_abi', {}).get('ports', [])
                if isinstance(row, dict)}
    retirement = all(name in physical for name in
                     ('rvfi_valid', 'rvfi_pc_rdata', 'rvfi_insn'))
    trap = 'rvfi_trap' in physical
    missing = [name for name in required if name not in physical]
    return dict(
        schema_version='p0_cpu_only_signal_status.v1',
        retirement='observed' if retirement else 'unknown',
        trap='observed' if trap else 'unknown',
        rvfi_trap='observed' if trap else 'unknown',
        required=list(required),
        missing_required=missing,
        exposed=sorted(name for name in ('rvfi_valid', 'rvfi_pc_rdata', 'rvfi_insn',
                                         'rvfi_trap', 'rvfi_rd_addr', 'rvfi_rd_wdata')
                       if name in physical),
        claim='only the exposed signals are observed; absent signals are unknown, not zero')


def _check_observations(selected: dict, config: dict) -> dict:
    status = _signal_status(selected['artifact'], config['required_observations'])
    if status['missing_required']:
        raise CpuOnlyError(
            'cpu-only-required-observation-missing:' +
            ','.join(status['missing_required']))
    return status


def _check_clock_shape(selected: dict) -> dict:
    """Refuse CPU artifacts this one-tick host cannot clock honestly.

    The host provides one free-running CPU clock and one normalized reset.  A
    generated CPU with several clock domains, a non-unit ratio or a timed model
    needs a different scheduler; silently driving one clock would be a false
    observation.
    """
    schedule = selected['artifact'].get('clock_schedule')
    if not isinstance(schedule, dict):
        raise CpuOnlyError('cpu-only-clock-schedule-missing')
    clocks = schedule.get('clocks')
    resets = schedule.get('resets')
    if not isinstance(clocks, list) or len(clocks) != 1:
        raise CpuOnlyError('cpu-only-clock-shape-unsupported:clocks=%d' %
                           (len(clocks) if isinstance(clocks, list) else 0))
    if not isinstance(resets, list) or len(resets) != 1:
        raise CpuOnlyError('cpu-only-clock-shape-unsupported:resets=%d' %
                           (len(resets) if isinstance(resets, list) else 0))
    clock = clocks[0]
    if (clock.get('ratio') != 1 or clock.get('half_period_fast_ticks') != 1
            or schedule.get('fast_frequency_hz') != clock.get('frequency_hz')):
        raise CpuOnlyError('cpu-only-clock-shape-unsupported:ratio')
    return dict(
        schema_version='p0_cpu_only_clock_status.v1',
        clocks=1, resets=1, signal=clock.get('signal'),
        reset_signal=resets[0].get('signal'),
        frequency_hz=clock.get('frequency_hz'),
        phase_policy=schedule.get('phase_policy'),
        claim='one host tick drives exactly one CPU clock and one normalized reset')


def _check_bus_shape(selected: dict) -> dict:
    """Classify the CPU's own memory endpoint into a shape this host serves.

    Three shapes are served, each a real RTL fact of the pinned wrapper's role
    map: separate OBI instruction/data channels (Ibex, CV32E40P), one classic
    Wishbone port (PicoRV32) or one AXI4-Lite port (PicoRV32).  A CPU whose role
    map fits none of them is refused by name with the endpoint and roles that
    were actually exported; no shape is inferred from a component name.
    """
    roles = _role_map(selected['artifact'])
    served = set()
    for protocol in BUS_PROTOCOLS:
        served.update(_BUS_ROLES[protocol])
    observed_endpoints = sorted({endpoint for endpoint, _ in roles
                                 if endpoint.startswith('processor.')})
    if not observed_endpoints:
        raise CpuOnlyError('cpu-only-bus-endpoint-missing')
    if not served & set(observed_endpoints):
        # The CPU has memory endpoints, but none of the shapes this host serves.
        # A packed/unified bundle (a 64-bit AXI4 `noc_req_o`/`noc_resp_i`, for
        # instance) is a different transactor, so this names the endpoint that
        # exists instead of claiming a missing role on a bus it does not have.
        raise CpuOnlyError('cpu-only-bus-endpoint-unsupported:' +
                           ','.join(observed_endpoints))
    missing = {}
    for protocol in BUS_PROTOCOLS:
        gaps = []
        for endpoint, names in _BUS_ROLES[protocol].items():
            for role in names:
                if (endpoint, role) not in roles:
                    gaps.append(endpoint + '.' + role)
        if not gaps:
            return _bus_document(roles, protocol)
        missing[protocol] = gaps
    best = min(missing, key=lambda name: (len(missing[name]), name))
    raise CpuOnlyError('cpu-only-bus-shape-unsupported:%s:%s' %
                       (best, ','.join(missing[best])))


def _bus_document(roles: dict, protocol: str) -> dict:
    shape = {}
    for endpoint, names in _BUS_ROLES[protocol].items():
        shape[endpoint] = dict((role, roles[(endpoint, role)]) for role in names)
    return dict(
        schema_version='p2_cpu_only_bus_status.v1',
        protocol=protocol,
        endpoints=sorted(shape),
        roles=shape,
        claim='only the roles named here are driven; error pins are tied inactive '
              'and the host never derives retirement from bus traffic',
    )


def _check_cpu_shape(selected: dict, config: dict) -> dict:
    status = _check_observations(selected, config)
    clock = _check_clock_shape(selected)
    status['clock'] = clock
    status['bus'] = _check_bus_shape(selected)
    return status


def _header(selected: dict, config: dict, model_kind: str,
            bus: dict) -> str:
    artifact = selected['artifact']
    roles = _role_map(artifact)
    ports = _port_map(artifact)
    protocol = bus['protocol']
    lines = [
        '#pragma once',
        '// Generated by scripts/inprocess_cpu_only.py. One CPU model only.',
        f'#define CPU_ONLY_MODEL_KIND "{model_kind}"',
        '#define CPU_MODEL Vlocal_cpu',
        f'#define {_BUS_DEFINES[protocol]} 1',
        f'#define CPU_BUS_NAME "{protocol}"',
        f'#define CPU_RAM_BASE {config["ram_base"]}u',
        f'#define CPU_RAM_SIZE {config["ram_size"]}u',
        f'#define CPU_BOOT {config["boot_address"]}u',
        f'#define CPU_RESET_ASSERT {config["reset_assert_ticks"]}u',
        f'#define CPU_RESET_RELEASE {config["reset_release_ticks"]}u',
        f'#define CPU_MAILBOX_ADDRESS {config["mailbox_address"]}u',
        f'#define CPU_RESULT_ADDRESS {config["result_address"]}u',
        f'#define CPU_DEFAULT_MAX_TICKS {config["max_ticks"]}u',
    ]
    for key, macro in _BUS_MACROS[protocol].items():
        if key in roles:
            lines.append(f'#define {macro} {roles[key]}')
    for physical, macro in (
            ('rvfi_valid', 'CPU_RVFI_VALID'), ('rvfi_order', 'CPU_RVFI_ORDER'),
            ('rvfi_pc_rdata', 'CPU_RVFI_PC_RDATA'), ('rvfi_insn', 'CPU_RVFI_INSN'),
            ('rvfi_rd_addr', 'CPU_RVFI_RD_ADDR'), ('rvfi_rd_wdata', 'CPU_RVFI_RD_WDATA'),
            ('rvfi_trap', 'CPU_RVFI_TRAP')):
        row = next((item for item in ports.values()
                    if item.get('physical_port') == physical), None)
        if row is not None:
            lines.append(f'#define {macro} {row["wrapper_name"]}')
    return '\n'.join(lines) + '\n'


def _link_host(selected: dict, config: dict, model: dict, bus: dict) -> dict:
    model_dir = Path(model['model_dir'])
    include = model_dir / 'include'
    include.mkdir(parents=True, exist_ok=True)
    header = include / 'cpu_only_config.h'
    header.write_text(_header(selected, config, model['model_kind'], bus),
                      encoding='utf-8')
    archive = Path(model['archive'])
    binary = model_dir / 'cpu-only-host'
    key = _sha(json.dumps({
        'host': _sha(HOST_SOURCE.read_bytes()), 'header': _sha(header.read_bytes()),
        'archive': model['archive_sha256'], 'kind': model['model_kind'],
    }, sort_keys=True).encode())
    stamp = model_dir / 'host.json'
    if stamp.is_file() and binary.is_file():
        try:
            document = _read_json(stamp)
            if (document.get('key') == key
                    and _sha(binary.read_bytes()) == document.get('binary_sha256')):
                return dict(status='cache_hit', host=str(binary), host_key=key,
                            binary_sha256=document['binary_sha256'],
                            header=str(header), link_seconds=0.0)
        except (OSError, ValueError, KeyError):
            pass
    toolchain = _toolchain()
    runtime_include = Path(toolchain['verilator']['runtime_root']) / 'include'
    command = [
        toolchain['cxx']['path'], '-std=c++17', '-O2',
        '-I' + str(include), '-I' + str(model_dir / 'obj'),
        '-I' + str(runtime_include), '-I' + str(runtime_include / 'vltstd'),
        str(HOST_SOURCE), str(archive),
        str(runtime_include / 'verilated.cpp'),
        str(runtime_include / 'verilated_threads.cpp'),
        '-pthread', '-latomic', '-o', str(binary),
    ]
    started = time.monotonic()
    result = subprocess.run(command, capture_output=True, text=True, cwd=ROOT)
    seconds = time.monotonic() - started
    (model_dir / 'link.log').write_text(
        '$ ' + ' '.join(command) + '\n' + result.stdout + result.stderr, encoding='utf-8')
    if result.returncode or not binary.is_file():
        raise CpuOnlyError('cpu-only-host-link-failed:' + (result.stdout + result.stderr)[-4000:])
    binary_sha = _sha(binary.read_bytes())
    _write_json(stamp, dict(schema_version='p0_cpu_only_host.v1', key=key,
                            binary_sha256=binary_sha, command=command,
                            link_seconds=seconds))
    return dict(status='built', host=str(binary), host_key=key,
                binary_sha256=binary_sha, header=str(header), link_seconds=seconds)


def _firmware_text(config: dict, *, fault: bool) -> str:
    address = config['program_address']
    words = _FAULT_PROGRAM_WORDS if fault else _PROGRAM_WORDS
    lines = []
    for index, word in enumerate(words):
        lines.append('%x %s' % (address + 4 * index,
                                bytes(word.to_bytes(4, 'little')).hex()))
    lines.append('%x %s' % (config['mailbox_address'],
                            bytes((0xef, 0xbe, 0xad, 0xde)).hex()))
    lines.append('%x %s' % (config['result_address'], '00000000'))
    return '\n'.join(lines) + '\n'


def build_cpu_only(config_path: str | Path = DEFAULT_CONFIG,
                   cache: str | Path = 'runs/p0-cpu-only/cache',
                   output: str | Path | None = None, *,
                   assertions: bool = False) -> dict:
    """Build (or reuse) the CPU-only model and host for one scenario.

    ``cache`` is the CPU-only model cache owned by this route.  The pinned CPU
    artifact itself is read from the scenario's ``artifact_cache``; no target IP
    or DMA artifact is ever selected.  The returned ``archives`` list contains
    exactly one model archive, the CPU's.
    """
    if type(assertions) is not bool:
        raise CpuOnlyError('cpu-only-assertions-bool')
    config = load_cpu_only_config(config_path)
    cache_path = _normalise_path(Path(cache))
    cache_path.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    resolved = resolve_cpu_artifact(config)
    selected = resolved['selected']
    signal_status = _check_cpu_shape(selected, config)
    bus = signal_status['bus']
    model_kind = 'assertion' if assertions else 'baseline'
    model_dir = cache_path / 'models' / (selected['digest'][:16] + '-' + model_kind)
    model = _verilator_build(selected, config, model_kind, model_dir)
    host = _link_host(selected, config, model, bus)
    artifact = dict(
        source=resolved['source'],
        cache_hit=resolved['cache_hit'],
        compiled_this_invocation=resolved['compiled_this_invocation'],
        build_digest=resolved['build_digest'],
        artifact_digest=resolved['artifact_digest'],
        artifact_cache=str(_artifact_cache_root(config)),
        kind=selected['artifact'].get('kind'),
        observation=resolved.get('observation'),
        rendered=resolved.get('rendered'),
        resolve_seconds=resolved.get('seconds'),
        note='the artifact is resolved from the profile and matched by its own '
             'artifact_digest; a miss is built with the local-harness machinery, '
             'a hit is reused as-is',
    )
    result = dict(
        schema_version='p2_cpu_only_build.v1',
        status='cache_hit' if model['status'] == 'cache_hit' and host['status'] == 'cache_hit' else 'built',
        config=config['_path'], cpu_profile=config['cpu_profile'],
        artifact_digest=selected['artifact'].get('artifact_digest'),
        artifact_cache=selected['cache_dir'],
        artifact=artifact,
        compiled_this_invocation=bool(
            resolved['compiled_this_invocation']
            or model['status'] == 'built' or host['status'] == 'built'),
        cache_hit=bool(resolved['cache_hit'] and model['status'] == 'cache_hit'
                       and host['status'] == 'cache_hit'),
        model_module='local_cpu', model_kind=model_kind,
        bus=bus,
        model=model, host=host,
        model_archive=model['archive'],
        archives=[dict(path=model['archive'], sha256=model['archive_sha256'],
                       kind='cpu', module='local_cpu')],
        assertions=assertions,
        assertion_flags=list(assertion_build_flags(rtl_assertions=assertions)),
        signal_status=signal_status,
        seconds=time.monotonic() - started,
    )
    if output is not None:
        output_path = _normalise_path(Path(output))
        output_path.mkdir(parents=True, exist_ok=True)
        _write_json(output_path / 'build.json', result)
    return result


def _parse_word(value) -> int:
    if isinstance(value, int) and not isinstance(value, bool):
        word = value
    elif isinstance(value, str):
        try:
            word = int(value, 0)
        except ValueError as error:
            raise CpuOnlyError('cpu-only-record-invalid:' + str(value)) from error
    else:
        raise CpuOnlyError('cpu-only-record-invalid:' + repr(value))
    if not 0 <= word <= 0xffffffff:
        raise CpuOnlyError('cpu-only-record-out-of-range')
    return word


def _fuzz_records(fuzz) -> tuple[list[int], dict]:
    if isinstance(fuzz, int) and not isinstance(fuzz, bool):
        fuzz = {'cases': fuzz}
    if not isinstance(fuzz, dict):
        raise CpuOnlyError('cpu-only-fuzz-invalid')
    cases = fuzz.get('cases', 16)
    seed = fuzz.get('seed', 1)
    if type(cases) is not int or not 1 <= cases <= 4096:
        raise CpuOnlyError('cpu-only-fuzz-cases')
    if type(seed) is not int:
        raise CpuOnlyError('cpu-only-fuzz-seed')
    generator = random.Random(seed)
    words = [generator.getrandbits(32) for _ in range(cases)]
    return words, dict(schema_version='p2_cpu_only_fuzz.v1', mode='data', seed=seed,
                       cases=cases,
                       generator='python-random.getrandbits(32)',
                       basis='one 32-bit mailbox word consumed by the pinned CPU program',
                       program_basis='pinned polling program (_PROGRAM_WORDS): load the '
                                     'mailbox word, add 1, store it to the result word',
                       mutation_basis='python-random.getrandbits(32) per case')


# --- generated-program batches ------------------------------------------------
#
# The generator and the gate are the repository's F1 ones.  This module builds
# only the firmware around them and compares the real retirement trace and the
# real data window with the reference model's expectation.


def _program_isa(config: dict):
    """The declared CPU ISA as the F1 generator/gate profile (RV32 only)."""
    from myfuzz.riscv.profile import ProfileError, RiscvProfile, profile_from_mapping
    try:
        document = _read_json(ROOT / config['cpu_profile'])
    except (OSError, ValueError) as error:
        raise CpuOnlyError('cpu-only-program-isa:' + str(error)) from error
    try:
        profile = profile_from_mapping(document)
    except ProfileError as error:
        raise CpuOnlyError('cpu-only-program-isa:' + str(error)) from error
    if profile.xlen != 32:
        raise CpuOnlyError('cpu-only-program-isa-not-rv32:%d' % profile.xlen)
    if 'I' not in profile.extensions:
        raise CpuOnlyError('cpu-only-program-isa-not-rv32i:' +
                           ','.join(sorted(profile.extensions)))
    # Only M is carried over: the generator emits it only when declared, and no
    # other declared extension changes an instruction of the emitted subset.
    extensions = frozenset(item for item in ('I', 'M')
                           if item in profile.extensions)
    return RiscvProfile(32, extensions, 4, 32, profile.reset_vector,
                        profile.component_id)


def _hi_lo(address: int) -> tuple[int, int]:
    """The LUI/ADDI pair for a 32-bit constant (ADDI's immediate is signed)."""
    low = ((address & 0xfff) + 0x800) % 0x1000 - 0x800
    return ((address - low) >> 12) & 0xfffff, low


def _program_preamble(address: int, register: int = 18) -> list[int]:
    """Set the F1 data-window base register before the program runs."""
    from myfuzz.scenario.rv32i_sources import Rv32iInstruction
    high, low = _hi_lo(address)
    return [Rv32iInstruction('LUI', rd=register, immediate=high).word(),
            Rv32iInstruction('ADDI', rd=register, rs1=register,
                             immediate=low).word()]


def _program_completion_store(offset: int) -> int:
    """One ``SW x0, offset(x18)``: the case's own completion evidence."""
    from myfuzz.scenario.rv32i_sources import Rv32iInstruction
    return Rv32iInstruction('SW', rs2=0, rs1=18, immediate=offset).word()


def _program_nop() -> int:
    from myfuzz.scenario.rv32i_sources import Rv32iInstruction
    return Rv32iInstruction('NOP').word()


def _fnv32(words, seed: int = 2166136261) -> int:
    """FNV-1a 32 over 32-bit little-endian words (the host's own hash)."""
    digest = seed
    for word in words:
        for byte in range(4):
            digest ^= (word >> (8 * byte)) & 0xff
            digest = (digest * 16777619) & 0xffffffff
    return digest


def _program_batch(config: dict, fuzz: dict) -> dict:
    """Generate one batch of different RV32 programs and its firmware image.

    Every case is a fresh program from ``generate_program`` admitted by
    ``validate_f1_program_record`` and executed by the reference model
    (``f1_reference_expectation``).  The firmware installs the case's preamble,
    program, completion store and NOP sled back to back, so the cases fall
    through one another in a single boot.
    """
    from myfuzz.fuzz.f1_program_gate import (
        F1GateFlags, f1_reference_expectation, trace_hash as f1_trace_hash,
        validate_f1_program_record)
    from myfuzz.fuzz.rv32_program import generate_program

    cases = fuzz.get('cases', 16)
    seed = fuzz.get('seed', 1)
    if type(cases) is not int or not 1 <= cases <= 4096:
        raise CpuOnlyError('cpu-only-fuzz-cases')
    if type(seed) is not int:
        raise CpuOnlyError('cpu-only-fuzz-seed')
    data_words = config.get('program_data_words', PROGRAM_DATA_WORDS)
    max_words = config.get('program_max_words', 8)
    window_bytes = data_words * 4
    done_offset = window_bytes
    flags = F1GateFlags(program_words=max_words)
    isa = _program_isa(config)
    code_base = config['program_address']
    data_base = config.get('program_data_address')
    if data_base is None:
        data_base = code_base + PROGRAM_CASE_STRIDE * 16
    image = {}
    rows = []
    metadata = []
    code = code_base
    for index in range(cases):
        program_rng = random.Random(seed * 1000003 + index)
        window_rng = random.Random(seed * 1000033 + index + 1)
        program = generate_program(
            isa, seed=program_rng.randrange(1 << 31), max_words=max_words,
            window_size=window_bytes, style='mixed', allow_auipc=False)
        words = tuple(program.words)
        slot = code
        start = slot + 4 * len(_program_preamble(0))
        record = {'words': list(words)}
        try:
            validate_f1_program_record(record, isa=isa, window_bytes=window_bytes,
                                       flags=flags, image_base=start)
        except ValueError as error:
            raise CpuOnlyError('cpu-only-program-gate:%d:%s' %
                               (index, error)) from error
        window_base = data_base + index * PROGRAM_CASE_STRIDE
        window = [window_rng.getrandbits(32) for _ in range(data_words)]
        memory = {window_base + 4 * offset: value
                  for offset, value in enumerate(window)}
        try:
            expectation = f1_reference_expectation(
                record, isa=isa, window_bytes=window_bytes, flags=flags,
                registers={18: window_base}, memory=memory,
                data_base=start, image_base=start, trace=True)
        except ValueError as error:
            raise CpuOnlyError('cpu-only-program-reference:%d:%s' %
                               (index, error)) from error
        final = list(window)
        for address, value in expectation['memory_changes'].items():
            offset = address - window_base
            if 0 <= offset < window_bytes and offset % 4 == 0:
                final[offset // 4] = value
        # The reference model reports a store's stored value as its trace
        # ``wdata``; RVFI states a retirement that writes no register with
        # ``rd_addr 0`` and ``rd_wdata 0``.  The hash is therefore taken over the
        # RVFI projection, exactly like the unified entry's ``f1_rvfi_trace``.
        projected = [dict(pc=entry['pc'], insn=entry['insn'],
                          insn_word=entry['insn_word'], rd=entry['rd'],
                          wdata=(entry['wdata'] if entry['rd'] else 0))
                     for entry in expectation['trace']]
        expected_trace_hash = f1_trace_hash(projected)
        trailer = start + 4 * len(words)
        done_address = window_base + done_offset
        for offset, word in enumerate(_program_preamble(window_base)):
            image[slot + 4 * offset] = word
        for offset, word in enumerate(words):
            image[start + 4 * offset] = word
        image[trailer] = _program_completion_store(done_offset)
        for offset in range(PROGRAM_SLED_WORDS):
            image[trailer + 4 + 4 * offset] = _program_nop()
        for offset, word in enumerate(window):
            image[window_base + 4 * offset] = word
        image[done_address] = PROGRAM_DONE_SENTINEL
        code = trailer + 4 + 4 * PROGRAM_SLED_WORDS
        metadata.append(dict(index=index, slot=slot, start=start,
                             end=trailer, trailer=trailer, data=window_base,
                             data_words=data_words, done=done_address,
                             done_value=PROGRAM_DONE_VALUE))
        rows.append(dict(
            index=index, words=['0x%08x' % word for word in words],
            program_sha256=_sha(b''.join(word.to_bytes(4, 'little')
                                         for word in words)),
            program_fnva32=_fnv32(words),
            slot=slot, program_start=start, program_end=trailer,
            data_base=window_base, data_words=data_words,
            data_initial=['0x%08x' % word for word in window],
            data_final=['0x%08x' % word for word in final],
            done_address=done_address, done_value=PROGRAM_DONE_VALUE,
            data_hash_before=_fnv32(window),
            data_hash_after=_fnv32(final),
            data_changed=sum(1 for before, after in zip(window, final)
                             if before != after),
            expectation=dict(
                retired_count=expectation['retired_count'],
                trace_hash=expected_trace_hash,
                trace_hash_value=int(expected_trace_hash.split(':')[-1], 16),
                reference_trace_hash=expectation['trace_hash'],
                pc_order=list(expectation['pc_order']),
                register_writes=[entry.get('rd') for entry
                                 in expectation['register_writes']
                                 if isinstance(entry, dict)],
                rd_mask=_register_mask(expectation['register_writes']),
                memory_changes=dict(('%08x' % address, '0x%08x' % value)
                                    for address, value in
                                    expectation['memory_changes'].items()),
            ),
            disassembly=[dict(pc='0x%08x' % entry['pc'], insn=entry['insn'],
                              insn_word='0x%08x' % entry['insn_word'],
                              rd=entry['rd'], wdata='0x%08x' % entry['wdata'])
                         for entry in projected],
        ))
    image[code] = _HALT_WORD
    for address in image:
        if address % 4:
            raise CpuOnlyError('cpu-only-program-image-unaligned:0x%x' % address)
        if not (config['ram_base'] <= address
                and address < config['ram_base'] + config['ram_size']):
            raise CpuOnlyError('cpu-only-program-image-outside-ram:0x%x' % address)
    firmware = '\n'.join('%x %s' % (address, image[address].to_bytes(4, 'little').hex())
                         for address in sorted(image)) + '\n'
    programs = '\n'.join(
        'prog %d start=0x%x end=0x%x data=0x%x data_words=%d done=0x%x '
        'done_value=0x%x trailer=0x%x' % (
            row['index'], row['start'], row['end'], row['data'],
            row['data_words'], row['done'], row['done_value'], row['trailer'])
        for row in metadata) + '\n'
    document = dict(
        schema_version='p2_cpu_only_fuzz.v1', mode='program', seed=seed,
        cases=cases,
        generator='myfuzz.fuzz.rv32_program.generate_program(style=mixed, '
                  'allow_auipc=False)',
        gate='myfuzz.fuzz.f1_program_gate.validate_f1_program_record',
        reference='myfuzz.fuzz.f1_program_gate.f1_reference_expectation',
        basis='one freshly generated RV32 program per case, installed in its own '
              'slot and really executed by the pinned CPU model',
        program_basis='different program per case: %d..%d words from the F1 '
                      'generator, admitted by the F1 program gate' %
                      (1 if max_words > 1 else 1, max_words),
        mutation_basis='none: every case is a fresh generation from its own seed '
                       'and is not a mutation of the previous case',
        isa=dict(xlen=isa.xlen, extensions=sorted(isa.extensions),
                 register_count=isa.register_count),
        window_bytes=window_bytes, program_max_words=max_words,
        code_base=code_base, data_base=data_base,
        image_words=len(image),
    )
    return dict(document=document, rows=rows, metadata=metadata,
                firmware=firmware, programs=programs, image=image)


def _register_mask(writes) -> int:
    """Bitmask of the registers the reference model really wrote."""
    mask = 0
    for entry in writes:
        register = entry.get('rd') if isinstance(entry, dict) else entry
        if isinstance(register, int) and register:
            mask |= 1 << register
    return mask


def _program_checks(row: dict, case: dict) -> dict:
    """Compare one executed case with its reference expectation, field by field."""
    expectation = row['expectation']
    checks = []

    def hex32(value):
        return '0x%08x' % value if isinstance(value, int) else value

    def check(name, expected, observed, *, hexadecimal=False):
        if hexadecimal:
            expected, observed = hex32(expected), hex32(observed)
        checks.append(dict(name=name, expected=expected, observed=observed,
                           ok=expected == observed))

    check('program_hash', row['program_fnva32'], case.get('program_hash'),
          hexadecimal=True)
    check('program_words', len(row['words']), case.get('program_words'))
    check('done', row['done_value'], case.get('done'), hexadecimal=True)
    check('data_hash_before', row['data_hash_before'],
          case.get('data_hash_before'), hexadecimal=True)
    check('data_hash_after', row['data_hash_after'],
          case.get('data_hash_after'), hexadecimal=True)
    check('data_changed', row['data_changed'], case.get('data_changed'))
    retirement_known = isinstance(case.get('retires'), int)
    if retirement_known:
        check('retires', expectation['retired_count'], case.get('retires'))
        check('trace_count', expectation['retired_count'], case.get('trace_count'))
        check('trace_hash', expectation['trace_hash_value'], case.get('trace'),
              hexadecimal=True)
        check('rd_mask', expectation['rd_mask'], case.get('rd_mask'),
              hexadecimal=True)
        check('pc_order', 1, case.get('pc_order'))
        check('insns_match', 1, case.get('insns_match'))
    failures = [item for item in checks if not item['ok']]
    return dict(
        index=row['index'],
        basis=('retirement-trace+data-window' if retirement_known
               else 'data-window+completion-store (this model exports no retirement)'),
        retirement_known=retirement_known,
        checks=checks, failures=failures, ok=not failures)


def _parse_case_lines(stdout: str) -> list[dict]:
    cases = []
    for line in stdout.splitlines():
        tokens = line.split()
        if len(tokens) < 3 or tokens[0] != 'case':
            continue
        try:
            index = int(tokens[1])
        except ValueError:
            continue
        status = tokens[2]
        fields = {}
        for token in tokens[3:]:
            if '=' not in token:
                continue
            key, value = token.split('=', 1)
            try:
                fields[key] = int(value, 0)
            except ValueError:
                fields[key] = value
        cases.append(dict(index=index, status=status, **fields))
    return cases


def _parse_summary(stdout: str) -> dict | None:
    for line in stdout.splitlines():
        tokens = line.split()
        if len(tokens) >= 2 and tokens[0] == 'summary':
            fields = {'status': tokens[1]}
            for token in tokens[2:]:
                if '=' not in token:
                    continue
                key, value = token.split('=', 1)
                try:
                    fields[key] = int(value, 0)
                except ValueError:
                    fields[key] = value
            return fields
    return None


def _parse_host_assertions(stdout: str) -> list[dict]:
    """Parse the host's own ``assertion tick=... case=... model=...`` lines."""
    events = []
    for line in stdout.splitlines():
        tokens = line.split()
        if not tokens or tokens[0] != 'assertion':
            continue
        fields = {}
        for token in tokens[1:]:
            if '=' not in token:
                continue
            key, value = token.split('=', 1)
            try:
                fields[key] = int(value, 0)
            except ValueError:
                fields[key] = value
        events.append(fields)
    return events


def _parse_assertion_lines(stream: str) -> list[dict]:
    events = []
    seen = set()
    for line in stream.splitlines():
        match = _ASSERTION_LINE.search(line)
        if match is None:
            continue
        file_name = match.group('file').strip()
        # Keep a repository-relative suffix; the cache prefix is run-specific.
        for prefix in ('third_party/', 'configs/', 'src/', 'scripts/'):
            position = file_name.find(prefix)
            if position >= 0:
                file_name = file_name[position:]
                break
        text = match.group('text').strip()
        key = (file_name, int(match.group('line')), text)
        if key in seen:
            continue
        seen.add(key)
        events.append(dict(
            kind='assertion', file=file_name, line=int(match.group('line')),
            scope=match.group('scope').strip(), text=text,
            source='Verilator %Error: Assertion failed (captured from child stdout/stderr)'))
    return events


def _parse_environment(stdout: str) -> list[dict]:
    events = []
    for line in stdout.splitlines():
        tokens = line.split()
        if not tokens or tokens[0] != 'environment_error':
            continue
        fields = {}
        for token in tokens[1:]:
            if '=' not in token:
                continue
            key, value = token.split('=', 1)
            try:
                fields[key] = int(value, 0)
            except ValueError:
                fields[key] = value
        events.append(dict(kind='environment_error', **fields))
    return events


def _fuzz_batch(config: dict, fuzz, fuzz_mode: str | None) -> dict:
    """Normalise one fuzz declaration into the documented input shapes.

    ``program`` (the option the unified entry defaults to) generates and executes
    a different RV32 program per case; ``data`` is the P0 shape, ``cases`` random
    32-bit mailbox words for the one pinned polling program.  A mapping without a
    ``mode`` keeps the P0 data shape, so an existing caller that never named a
    mode is not silently moved to instruction fuzz.
    """
    if isinstance(fuzz, int) and not isinstance(fuzz, bool):
        fuzz = {'cases': fuzz}
    if not isinstance(fuzz, dict):
        raise CpuOnlyError('cpu-only-fuzz-invalid')
    declared = fuzz.get('mode')
    if fuzz_mode is not None and declared is not None and declared != fuzz_mode:
        raise CpuOnlyError('cpu-only-fuzz-mode-conflict:%s:%s' %
                           (declared, fuzz_mode))
    mode = declared if declared is not None else (fuzz_mode or 'data')
    if not isinstance(mode, str) or mode not in ('data', 'program'):
        raise CpuOnlyError('cpu-only-fuzz-mode:' + str(mode))
    if mode == 'program':
        batch = _program_batch(config, fuzz)
        return dict(mode='program', words=[], document=batch['document'],
                    batch=batch, cases=batch['document']['cases'])
    words, document = _fuzz_records(fuzz)
    return dict(mode='data', words=words, document=document, batch=None,
                cases=len(words))


def run_cpu_only(config_path: str | Path = DEFAULT_CONFIG,
                 cache: str | Path = 'runs/p0-cpu-only/cache',
                 output: str | Path = 'runs/p0-cpu-only/run', *,
                 records=None, fuzz=None, max_ticks: int | None = None,
                 assertions: bool | None = None, fault=None,
                 timeout: float | None = None, quiet: bool = True,
                 fuzz_mode: str | None = None) -> dict:
    """Run one CPU-only fixed-record, fuzz or declared assertion fault batch.

    ``records`` is a sequence of 32-bit mailbox words for the pinned polling
    program.  ``fuzz`` is a mapping ``{cases, seed, mode}`` (or an integer case
    count): ``mode='program'`` generates a different RV32 program per case and
    really executes it, ``mode='data'`` is the P0 data-only shape.  A mapping with
    no ``mode`` keeps the P0 data shape unless ``fuzz_mode`` names one.

    ``fault`` is ``True`` (use the scenario's declared fault) or a mapping with
    ``kind``/``tick``.  Assertions default to off for a normal batch and on for
    the fault case; an assertion build is selected automatically for a fault.
    """
    config = load_cpu_only_config(config_path)
    fault_case = None
    if fault is True:
        fault_case = config.get('fault')
        if fault_case is None:
            raise CpuOnlyError('cpu-only-fault-not-declared')
    elif isinstance(fault, dict):
        fault_case = fault
    elif fault not in (None, False):
        raise CpuOnlyError('cpu-only-fault-invalid')
    if fault_case is not None:
        if fault_case.get('kind') != 'spurious-data-rvalid':
            raise CpuOnlyError('cpu-only-fault-kind')
        if type(fault_case.get('tick')) is not int:
            raise CpuOnlyError('cpu-only-fault-tick')
        if assertions is False:
            raise CpuOnlyError('cpu-only-fault-needs-assertions')
        assertions = True
    if assertions is None:
        assertions = fault_case is not None
    if type(assertions) is not bool:
        raise CpuOnlyError('cpu-only-assertions-bool')
    max_ticks = config['max_ticks'] if max_ticks is None else max_ticks
    if type(max_ticks) is not int or not 1 <= max_ticks <= 1000000:
        raise CpuOnlyError('cpu-only-max-ticks')
    fuzz_document = None
    fuzz_batch = None
    fuzz_shape = None
    if fault_case is not None:
        words = []
        input_mode = 'fault'
    elif fuzz is not None:
        shapes = _fuzz_batch(config, fuzz, fuzz_mode)
        words, fuzz_document = shapes['words'], shapes['document']
        fuzz_batch, fuzz_shape = shapes['batch'], shapes['mode']
        input_mode = 'fuzz'
    elif records is not None:
        words = [_parse_word(value) for value in records]
        input_mode = 'records'
    else:
        words = [_parse_word(value) for value in config.get('records', [])]
        input_mode = 'records'
    if fault_case is None and fuzz_batch is None and not words:
        raise CpuOnlyError('cpu-only-records-empty')
    output_path = _normalise_path(Path(output))
    output_path.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    build = build_cpu_only(config_path, cache, output=None, assertions=assertions)
    protocol = build['bus']['protocol']
    if fault_case is not None and protocol != 'obi':
        # The declared fault is a spurious response on the OBI data channel; a
        # unified Wishbone/AXI port has no such channel, so this route refuses by
        # name instead of inventing a different fault.
        raise CpuOnlyError('cpu-only-fault-bus-unsupported:' + protocol)
    firmware = output_path / 'firmware.txt'
    command = [build['host']['host'], '--firmware', str(firmware),
               '--max-ticks', str(max_ticks),
               '--assertions', 'on' if assertions else 'off']
    if quiet:
        command.append('--quiet')
    if fuzz_batch is not None:
        firmware.write_text(fuzz_batch['firmware'], encoding='utf-8')
        programs_path = output_path / 'programs.txt'
        programs_path.write_text(fuzz_batch['programs'], encoding='utf-8')
        command += ['--programs', str(programs_path)]
        case_total = fuzz_batch['document']['cases']
    else:
        firmware.write_text(_firmware_text(config, fault=fault_case is not None),
                            encoding='utf-8')
        programs_path = None
        if fault_case is not None:
            command += ['--fault', fault_case['kind'], '--fault-tick', str(fault_case['tick'])]
        else:
            command += ['--records', ','.join(str(word) for word in words)]
        case_total = len(words)
    (output_path / 'command.txt').write_text(' '.join(command) + '\n', encoding='utf-8')
    run_started = time.monotonic()
    if timeout is None:
        timeout = max(60.0, 30.0 + 0.02 * float(max_ticks) * max(1, case_total))
    try:
        process = subprocess.run(command, capture_output=True, text=True,
                                 cwd=ROOT, timeout=timeout)
        returncode, stdout, stderr = process.returncode, process.stdout, process.stderr
    except subprocess.TimeoutExpired as error:
        stdout = error.stdout.decode() if isinstance(error.stdout, bytes) else (error.stdout or '')
        stderr = error.stderr.decode() if isinstance(error.stderr, bytes) else (error.stderr or '')
        returncode = -9
        stderr += '\n[runner] child process timed out\n'
    wall = time.monotonic() - run_started
    (output_path / 'stdout.log').write_text(stdout, encoding='utf-8')
    (output_path / 'stderr.log').write_text(stderr, encoding='utf-8')
    cases = _parse_case_lines(stdout)
    summary = _parse_summary(stdout)
    # Verilator's assertion report is written by its own runtime (VL_WRITEF);
    # depending on the release it lands on the child's stdout rather than stderr.
    # Both streams are captured, so the exact text/file/line is retained either way.
    assertion_events = _parse_assertion_lines(stderr + '\n' + stdout)
    host_assertions = _parse_host_assertions(stdout)
    for index, event in enumerate(assertion_events):
        # The host's own event owns tick/case/model; an abort fallback without a
        # host line still keeps the Verilator text/file/line.
        owner = host_assertions[min(index, len(host_assertions) - 1)] if host_assertions else {}
        event.update(
            tick=owner.get('tick'), case=owner.get('case'),
            model=owner.get('model', 'cpu'), instance=owner.get('model', 'cpu'),
            got_error=owner.get('got_error'), got_finish=owner.get('got_finish'),
            fault=owner.get('fault'), input=owner.get('input'))
    environment_events = _parse_environment(stdout)
    expected = (fault_case or {}).get('expected_assertions') or []
    missing = [name for name in expected
               if not any(name in (event.get('scope', '') + ' ' + event.get('text', ''))
                          for event in assertion_events)]
    if fault_case is not None:
        if returncode == 3 or assertion_events:
            status = 'assertion_failed' if not missing else 'failed'
        elif returncode == 4:
            status = 'environment_failed'
        elif returncode == -9:
            status = 'environment_failed'
            environment_events.append(dict(kind='environment_error',
                                           reason='child_timeout', tick=0))
        else:
            status = 'failed'
            if not assertion_events:
                environment_events.append(dict(kind='environment_error',
                                               reason='assertion_not_triggered', tick=0))
    elif returncode == 0:
        status = 'observations_passed'
    elif returncode in (3, 4):
        status = 'assertion_failed' if returncode == 3 else 'environment_failed'
    else:
        status = 'failed'
    if fault_case is None and returncode == 3 and not assertion_events:
        # A child that aborted before the host's own event line is still a
        # captured assertion, but the runner must not claim it saw the text.
        status = 'failed'
    program_checks = []
    program_failure = None
    if fuzz_batch is not None:
        by_index = {}
        for case in cases:
            by_index.setdefault(case.get('index'), case)
        for row in fuzz_batch['rows']:
            case = by_index.get(row['index'])
            if case is None:
                program_checks.append(dict(
                    index=row['index'], basis='missing-case', checks=[],
                    ok=False, retirement_known=False,
                    failures=[dict(name='case-line', expected='present',
                                   observed='absent', ok=False)]))
                continue
            program_checks.append(_program_checks(row, case))
        failed_checks = [check for check in program_checks if not check['ok']]
        if status == 'observations_passed' and (
                failed_checks or len(cases) != len(fuzz_batch['rows'])):
            status = 'failed'
            if failed_checks:
                first = failed_checks[0]
                program_failure = ('case %d %s' % (
                    first['index'],
                    ', '.join('%s expected %r observed %r' %
                              (item['name'], item['expected'], item['observed'])
                              for item in first['failures'])))
            else:
                program_failure = 'case count %d != %d' % (
                    len(cases), len(fuzz_batch['rows']))
            program_failure = 'correspondence: ' + program_failure
    result = dict(
        schema_version='p0_cpu_only_run.v1',
        status=status, returncode=returncode,
        config=config['_path'], cpu_profile=config['cpu_profile'],
        model_module='local_cpu', model_kind=build['model_kind'],
        model_archive=build['model_archive'],
        archives=build['archives'],
        assertions=assertions,
        assertion_flags=build['assertion_flags'],
        signal_status=build['signal_status'],
        input_mode=input_mode,
        fuzz_mode=fuzz_shape,
        fuzz=fuzz_document,
        program_basis=(fuzz_document or {}).get('program_basis'),
        mutation_basis=(fuzz_document or {}).get('mutation_basis'),
        records=['0x%08x' % word for word in words],
        programs=(fuzz_batch['rows'] if fuzz_batch is not None else []),
        program_checks=program_checks,
        failure=program_failure,
        bus=build['bus'],
        artifact=build['artifact'],
        compiled_this_invocation=build['compiled_this_invocation'],
        cache_hit=build['cache_hit'],
        programs_file=(str(programs_path) if programs_path is not None else None),
        max_ticks=max_ticks,
        cases=cases, case_count=len(cases),
        summary=summary,
        assertion_events=assertion_events,
        host_assertion_events=host_assertions,
        environment_events=environment_events,
        expected_assertions=list(expected),
        missing_assertions=missing,
        fault=fault_case,
        host=build['host']['host'],
        host_binary_sha256=build['host']['binary_sha256'],
        model=build['model'],
        build_seconds=build['seconds'], wall_seconds=wall,
        output=str(output_path),
        stdout=str(output_path / 'stdout.log'), stderr=str(output_path / 'stderr.log'),
    )
    _write_json(output_path / 'result.json', result)
    return result


