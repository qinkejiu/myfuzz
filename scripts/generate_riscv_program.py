#!/usr/bin/env python3
"""Generate a seeded straight-line RISC-V program for a CPU component profile.

Writes a new directory containing ``program.json`` (four-byte records plus
per-instruction PC/assembly/extension metadata) and ``program.S`` (the same
words as ``.word``/``.2byte`` directives with assembly comments).  The records
are directly usable as ``--record F1:<hex>`` or in a records file.

This script only uses ``myfuzz.riscv``; it does not start RTL or touch the
runtime.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from myfuzz.riscv.profile import ProfileError, load_profile  # noqa: E402
from myfuzz.riscv.program import generate_program  # noqa: E402


def _assembly(program) -> str:
    lines = [
        "# generated by scripts/generate_riscv_program.py",
        f"# seed={program.seed} count={len(program.records)} "
        f"xlen={program.profile.xlen} "
        f"extensions={','.join(sorted(program.profile.extensions))}",
        ".section .text",
        ".globl _start",
        "_start:",
    ]
    for item in program.instructions:
        lines.append(f"    # pc=0x{item.pc:x} {item.assembly}")
        directive = ".2byte" if item.width == 2 else ".word"
        lines.append(f"    {directive} 0x{item.word:0{item.width * 2}x}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", required=True, help="CPU component profile JSON")
    parser.add_argument("--seed", required=True, type=int)
    parser.add_argument("--count", required=True, type=int,
                        help="number of four-byte records")
    parser.add_argument("--ram-base", type=lambda text: int(text, 0), default=0,
                        help="declared RAM window base (default 0)")
    parser.add_argument("--ram-size", type=lambda text: int(text, 0), default=0,
                        help="declared RAM window size; 0 disables memory ops")
    parser.add_argument("--compressed", action="store_true",
                        help="force two F1-safe 16-bit instructions per slot")
    parser.add_argument("--include-non-f1", action="store_true",
                        help="also use A/RV64 words the legacy F1 validator rejects")
    parser.add_argument("--no-assembly", action="store_true",
                        help="skip program.S")
    parser.add_argument("--output", required=True, help="new output directory")
    args = parser.parse_args(argv)

    try:
        profile = load_profile(args.profile)
        program = generate_program(
            profile, seed=args.seed, count=args.count,
            ram_base=args.ram_base, ram_size=args.ram_size,
            include_non_f1=args.include_non_f1,
            compressed=True if args.compressed else None,
        )
    except (ProfileError, ValueError) as error:
        parser.error(str(error))

    output = Path(args.output)
    try:
        output.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        parser.error(f"output directory already exists: {output}")
    (output / "program.json").write_text(
        json.dumps(program.as_dict(), indent=2) + "\n", encoding="utf-8")
    # A bare JSON string array, directly usable as --records-file.
    (output / "records.json").write_text(
        json.dumps(list(program.f1_records), indent=2) + "\n",
        encoding="utf-8")
    if not args.no_assembly:
        (output / "program.S").write_text(_assembly(program), encoding="utf-8")

    extension_counts: dict[str, int] = {}
    for item in program.instructions:
        extension_counts[item.extension] = extension_counts.get(item.extension, 0) + 1
    print(f"profile={profile.component_id or args.profile} xlen={profile.xlen} "
          f"extensions={','.join(sorted(profile.extensions))}")
    print(f"records={len(program.records)} instructions={len(program.instructions)} "
          f"by_extension={json.dumps(extension_counts, sort_keys=True)}")
    print(f"wrote {output / 'program.json'}")
    print(f"wrote {output / 'records.json'}")
    if not args.no_assembly:
        print(f"wrote {output / 'program.S'}")
    print("first record:", program.f1_records[0])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
